import { expect, test } from '@playwright/test'

test('생년월일을 입력하면 사주와 근거가 표시된다', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '나의 사주를 천천히 읽어보세요' })).toBeVisible()
  await page.getByLabel('태어난 해').fill('1986')
  await page.getByLabel('태어난 달').selectOption('5')
  await page.getByLabel('태어난 날').selectOption('29')
  await page.getByLabel('태어난 시', { exact: true }).selectOption('0')
  await page.getByLabel('태어난 분').selectOption('32')
  await page.getByRole('radio', { name: '남성' }).check()
  await page.getByRole('button', { name: '사주 살펴보기' }).click()
  await expect(page.getByTestId('pillars')).toContainText('丙寅')
  await expect(page.getByTestId('pillars')).toContainText('癸巳')
  await expect(page.getByTestId('pillars')).toContainText('癸酉')
  await expect(page.getByTestId('pillars')).toContainText('십이운성')
  await expect(page.getByTestId('natal-evidence')).toContainText('원국 관계 근거')
  await expect(page.getByTestId('natal-evidence')).toContainText('육해')
  await expect(page.getByTestId('seasonal-harmony')).toContainText('한난조습')
  await expect(page.getByTestId('seasonal-harmony')).toContainText('辛')
  await expect(page.getByTestId('seasonal-harmony')).toContainText('庚')
  await expect(page.getByTestId('seasonal-harmony')).toContainText('이 사주에 이 이미지가 필요한 이유')
  await expect(page.getByTestId('seasonal-harmony')).toContainText('개운은 운명을 바꾸는 주문이 아닙니다')
  await expect(page.getByTestId('seasonal-harmony')).toContainText('휴대폰 배경화면')
  await expect(page.getByRole('img', { name: '계절 균형 이미지' })).toBeVisible()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '이 개운 이미지 저장하기' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/^sai-seasonal-balance-.*\.jpg$/)
  await expect(page.getByRole('heading', { name: '사주 해석' })).toBeVisible()
  await expect(page.getByTestId('interpretation')).toContainText('전체 흐름')
  await expect(page.getByTestId('interpretation')).toContainText('직업과 일')
  await expect(page.getByTestId('interpretation')).toContainText('재물과 관리')
  await expect(page.getByTestId('interpretation')).toContainText('배우자와 결혼')
  await expect(page.getByTestId('interpretation')).toContainText('가족과 원가족')
  await expect(page.getByTestId('interpretation')).toContainText('자녀와 후배')
  await expect(page.getByTestId('interpretation')).toContainText('학업과 자격')
  await expect(page.getByTestId('interpretation')).toContainText('관계와 소통')
  await page.getByRole('tab', { name: /甲午.*1989.*1998/ }).click()
  await expect(page.getByTestId('cycle-detail')).toContainText('甲午 대운')
  await page.getByRole('tab', { name: /1989년.*己巳/ }).click()
  await expect(page.getByTestId('annual-detail')).toContainText('1989년')
  await expect(page.getByTestId('annual-detail')).toContainText('배우자')
  await expect(page.getByTestId('annual-detail')).toContainText('판정 근거')
  await expect(page.getByTestId('annual-detail')).toContainText('십이운성')
  await expect(page.getByTestId('annual-detail')).not.toContainText('巳巳')
  await page.getByRole('tab', { name: /1990년.*庚午/ }).click()
  await expect(page.getByTestId('annual-detail')).toContainText('1990년')
  await expect(page.getByTestId('annual-detail')).not.toContainText('1989년')
  await expect(page.getByRole('tab', { name: /1990년.*庚午/ })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('heading', { name: '계산 기준과 출처' })).toBeVisible()
  await expect(page.locator('body')).not.toHaveCSS('overflow-x', 'scroll')
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)
  expect(overflow).toBe(true)
})

test('필수 동의 없이 계산하지 않는다', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('개인정보 처리 안내에 동의').uncheck()
  await page.getByRole('button', { name: '사주 살펴보기' }).click()
  await expect(page.getByRole('alert')).toContainText('동의')
})
