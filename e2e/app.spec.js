import { expect, test } from '@playwright/test'

test('생년월일을 입력하면 사주와 근거가 표시된다', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '휴대폰에 저장해 두는 나만의 대박 배경화면' })).toBeVisible()
  await page.getByLabel('태어난 해').fill('1986')
  await page.getByLabel('태어난 달').selectOption('5')
  await page.getByLabel('태어난 날').selectOption('29')
  await page.getByLabel('태어난 시', { exact: true }).selectOption('0')
  await page.getByLabel('태어난 분').selectOption('32')
  await page.getByRole('radio', { name: '남성' }).check()
  await page.getByRole('button', { name: '내 대박 배경화면 받기' }).click()
  await expect(page.getByTestId('pillars')).toContainText('丙寅')
  await expect(page.getByTestId('luck-hero')).toContainText('총운에서 고른 개운 이미지')
  await expect(page.getByTestId('luck-hero')).toContainText('우선 보완')
  if (await page.evaluate(() => innerWidth < 700)) {
    const toggle = page.getByRole('button', { name: '총운 전체 읽기' })
    await expect(toggle).toBeVisible()
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    await toggle.click()
    await expect(page.locator('.overall-toggle')).toHaveAttribute('aria-expanded', 'true')
  }
  const imageFirst = await page.evaluate(() => {
    const hero = document.querySelector('[data-testid="luck-hero"]')
    const pillars = document.querySelector('[data-testid="pillars"]')
    return Boolean(hero && pillars && (hero.compareDocumentPosition(pillars) & Node.DOCUMENT_POSITION_FOLLOWING))
  })
  expect(imageFirst).toBe(true)
  await expect(page.getByTestId('pillars')).toContainText('癸巳')
  await expect(page.getByTestId('pillars')).toContainText('癸酉')
  await expect(page.getByTestId('pillars')).toContainText('십이운성')
  await expect(page.getByTestId('natal-evidence')).toContainText('원국 관계 근거')
  await expect(page.getByTestId('natal-evidence')).toContainText('육해')
  await expect(page.getByTestId('seasonal-harmony')).toContainText('월령표')
  await expect(page.getByTestId('overall-reading')).toContainText('먼저 읽는 총운')
  const narrativeOrder = await page.evaluate(() => {
    const overall = document.querySelector('[data-testid="overall-reading"]')
    const imageReason = document.querySelector('[data-testid="seasonal-harmony"]')
    return Boolean(overall && imageReason && (overall.compareDocumentPosition(imageReason) & Node.DOCUMENT_POSITION_FOLLOWING))
  })
  expect(narrativeOrder).toBe(true)
  await expect(page.getByTestId('seasonal-harmony')).toContainText('금(金)')
  await expect(page.getByTestId('seasonal-harmony')).toContainText('목(木)')
  await expect(page.getByTestId('seasonal-harmony')).toContainText('이 사주에 이 이미지가 필요한 이유')
  await expect(page.getByTestId('seasonal-harmony')).toContainText('개운은 운명을 바꾸는 주문이 아닙니다')
  await expect(page.getByTestId('seasonal-harmony')).toContainText('휴대폰 배경화면')
  await expect(page.getByRole('img', { name: '계절 균형 이미지' })).toBeVisible()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '휴대폰에 이미지 저장' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/^sai-seasonal-balance-.*\.jpg$/)
  await expect(page.getByRole('heading', { name: '삶의 여러 장면' })).toBeVisible()
  await expect(page.getByTestId('overall-reading')).toContainText('癸 일간')
  await expect(page.getByTestId('interpretation')).toContainText('직업과 일')
  await expect(page.getByTestId('interpretation')).toContainText('재물과 관리')
  await expect(page.getByTestId('interpretation')).toContainText('배우자와 결혼')
  await expect(page.getByTestId('interpretation')).toContainText('가족과 원가족')
  await expect(page.getByTestId('interpretation')).toContainText('자녀와 후배')
  await expect(page.getByTestId('interpretation')).toContainText('학업과 자격')
  await expect(page.getByTestId('interpretation')).toContainText('관계와 소통')
  await page.getByRole('tab', { name: /甲午.*1989.*1998/ }).click()
  await expect(page.getByTestId('cycle-detail')).toContainText('甲午 대운')
  await page.getByRole('tab', { name: /1989년.*己巳/ }).click()
  await expect(page.getByTestId('annual-detail')).toContainText('1989년')
  await expect(page.getByTestId('annual-detail')).toContainText('배우자')
  await expect(page.getByTestId('annual-detail')).toContainText('판정 근거')
  await expect(page.getByTestId('annual-detail')).toContainText('십이운성')
  await expect(page.getByTestId('annual-detail')).not.toContainText('巳巳')
  await page.getByRole('tab', { name: /1990년.*庚午/ }).click()
  await expect(page.getByTestId('annual-detail')).toContainText('1990년')
  await expect(page.getByTestId('annual-detail')).not.toContainText('1989년')
  await expect(page.getByRole('tab', { name: /1990년.*庚午/ })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('heading', { name: '계산 기준과 출처' })).toBeVisible()
  await expect(page.locator('body')).not.toHaveCSS('overflow-x', 'scroll')
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)
  expect(overflow).toBe(true)
})

test('예시 명식은 개인 물상 이미지와 쉬운 명리 설명을 보여 준다', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('태어난 해').fill('1987')
  await page.getByLabel('태어난 달').selectOption('1')
  await page.getByLabel('태어난 날').selectOption('25')
  await page.getByLabel('태어난 시', { exact: true }).selectOption('18')
  await page.getByLabel('태어난 분').selectOption('30')
  await page.getByRole('radio', { name: '남성' }).check()
  await page.getByRole('button', { name: '내 대박 배경화면 받기' }).click()

  await expect(page.getByTestId('pillars')).toContainText('丙寅')
  await expect(page.getByTestId('pillars')).toContainText('辛丑')
  await expect(page.getByTestId('pillars')).toContainText('甲戌')
  await expect(page.getByTestId('pillars')).toContainText('癸酉')
  const hero = page.getByTestId('luck-hero')
  const natalCanvas = hero.locator('canvas[data-layered-canvas="natal"]')
  await expect(natalCanvas).toHaveAttribute('data-layer-count', '4')
  await expect(natalCanvas).toHaveAttribute('data-layer-ready', 'true')
  await expect(hero).toContainText('내 사주 원국 물상 이미지')
  await expect(hero).toContainText('차가운 늦겨울, 따뜻한 빛과 맑은 물을 받는 푸른 개')
  await expect(hero.locator('.visual-tags span')).toHaveCount(5)
  await expect(hero).toContainText('#큰나무의기상')
  await expect(hero).toContainText('그림부터 읽는 총운')
  await expect(hero).toContainText('갑술일주(푸른 개)')
  await expect(hero).toContainText('술토(불씨를 품은 늦가을의 마른 땅)')
  await expect(hero).toContainText('신축월(차갑고 습한 늦겨울)')
  await expect(hero.getByRole('button', { name: '휴대폰에 이미지 저장' })).toHaveCount(0)

  const story = page.getByTestId('visual-story')
  await expect(story).toContainText('그림으로 읽는 내 사주')
  await expect(story).toContainText('갑술일주(푸른 개)')
  await expect(story).toContainText('갑목(곧게 자라는 큰 나무)')
  await expect(story).toContainText('병화(태양)')
  await expect(story).toContainText('정화(가까이 머무는 온기)')
  await expect(story).toContainText('계수(이슬과 맑은 물)')
  await expect(story).toContainText('이미 가진 힘')
  await expect(story).toContainText('더 필요한 작용')
  await expect(story).toContainText('유금 → 계수 → 갑목')
  await expect(page.getByTestId('seasonal-harmony')).not.toContainText('판정 근거와 한계')

  const luckImage = page.getByTestId('final-luck-image')
  const luckCanvas = luckImage.locator('canvas[data-layered-canvas="luck"]')
  await expect(luckImage).toContainText('12 · 나만의 개운 이미지')
  await expect(luckImage).toContainText('따뜻한 온기와 맑은 물을 받아 힘을 얻는 푸른 개')
  await expect(luckCanvas).toHaveAttribute('data-layer-count', '5')
  await expect(luckCanvas).toHaveAttribute('data-layer-ready', 'true')
  await expect(luckImage.getByRole('button', { name: '휴대폰에 이미지 저장' })).toBeVisible()
  const luckIsTwelfth = await page.evaluate(() => {
    const cycles = document.querySelector('[data-testid="luck-explorer"]')
    const finalImage = document.querySelector('[data-testid="final-luck-image"]')
    return Boolean(cycles && finalImage && (cycles.compareDocumentPosition(finalImage) & Node.DOCUMENT_POSITION_FOLLOWING))
  })
  expect(luckIsTwelfth).toBe(true)
})

